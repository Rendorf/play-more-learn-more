// Usage: node tools/make-curriculum-map.mjs
// Writes docs/product/curriculum-map.md from the grade files (unit and skill titles and blurbs).
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const units = [], skills = [];
const ctx = {
  console, Math, JSON, Number, String, Array, Object, Set, Map,
  PMLM: {
    registerUnit: u => units.push(u),
    registerSkill: s => skills.push(s),
  },
};
vm.createContext(ctx);
const load = f => vm.runInContext(fs.readFileSync(f, 'utf8') + '\n;this.U = typeof U !== "undefined" ? U : this.U;', ctx, { filename: f });
load(path.join(root, 'src/util.js'));
for (let g = 1; g <= 9; g++) load(path.join(root, `src/grade${g}.js`));

const build = (fs.readFileSync(path.join(root, 'index.html'), 'utf8').match(/const BUILD = '([^']+)'/) || [])[1] || 'unknown';
const stage = g => g <= 6 ? `Primary Stage ${g}` : `Lower Secondary Stage ${g}`;
let out = `# Curriculum map

**Who this is for:** teachers, schools, partners and content authors who want to see exactly what the game covers.
**Last checked against:** BUILD ${build}. Generated by \`node tools/make-curriculum-map.mjs\` from \`src/grade1.js\` … \`src/grade9.js\` (unit and skill titles and blurbs as children see them). Don't edit by hand.

Every skill has a 3–5 card lesson ending in a worked example, and questions at three levels; level 3 is the full Cambridge stage expectation. Every unit ends with a boss round. See [learning-design.md](learning-design.md) for how mastery works.

| Grade | Units | Skills |
|---|---|---|
`;
for (let g = 1; g <= 9; g++) out += `| ${g} (${stage(g)}) | ${units.filter(u => u.grade === g).length} | ${skills.filter(s => s.grade === g).length} |\n`;
out += `| **Total** | **${units.length}** | **${skills.length}** |\n`;
for (let g = 1; g <= 9; g++) {
  out += `\n## Grade ${g} — ${stage(g)}\n`;
  for (const u of units.filter(u => u.grade === g)) {
    out += `\n### ${u.icon} ${u.name}\n\n| Skill | What the child does |\n|---|---|\n`;
    for (const s of skills.filter(s => s.unit === u.id)) out += `| ${s.icon} ${s.title} | ${s.blurb} |\n`;
  }
}
fs.writeFileSync(path.join(root, 'docs/product/curriculum-map.md'), out);
console.log(`${units.length} units, ${skills.length} skills`);
